// Helper to create seed lead with auto-calculated score
function makeLead(params: {
  id: string;
  name: string;
  specialty: Lead['specialty'];
  country: 'Ireland' | 'Malta';
  city: string;
  hasWebsite: Lead['hasWebsite'];
  reviews: number;
  rating: number;
  gbp: Lead['gbpStatus'];
  owner: string;
  ownerRole: string;
  source: Lead['source'];
  sourcePartnerId?: string;
  stage: Lead['stage'];
  lostReason?: Lead['lostReason'];
  notNowUntil?: string;
  assignedTo: string;
  criteria: [number, number, number, number, number, number, number];
  disqualifiers?: [boolean, boolean];
  email: string;
  phone?: string;
  linkedin?: string;
  createdAt: string;
  milestones?: Partial<Lead>;
  notes?: string;
}): Lead {
  const [c1, c2, c3, c4, c5, c6, c7] = params.criteria;
  const [dq1, dq2] = params.disqualifiers || [false, false];

  const score = calculateLeadScore(
    {
      privateServices: c1 as any,
      googleReviews: c2 as any,
      websiteGap: c3 as any,
      gbpGaps: c4 as any,
      ownerAccessibility: c5 as any,
      recentActivity: c6 as any,
      scaleFit: c7 as any,
    },
    { corporateChain: dq1, fullyPublicFunded: dq2 }
  );

  const channels: Lead['channels'] = [
    {
      id: `${params.id}_ch1`,
      type: 'Email',
      value: params.email,
      status:
        params.stage === 'New Lead'
          ? 'Not contacted'
          : params.stage === 'Contacted'
          ? 'Contacted'
          : params.stage === 'Replied' || params.stage === 'Audit Sent' || params.stage === 'Won'
          ? 'Replied'
          : 'Contacted',
      lastContactedAt: params.stage !== 'New Lead' ? '2026-09-20' : undefined,
    },
  ];

  if (params.phone) {
    channels.push({
      id: `${params.id}_ch2`,
      type: 'Phone',
      value: params.phone,
      status: 'Not contacted',
    });
  }

  if (params.linkedin) {
    channels.push({
      id: `${params.id}_ch3`,
      type: 'LinkedIn',
      value: params.linkedin,
      status: params.stage === 'Replied' ? 'Replied' : 'Not contacted',
    });
  }

  return {
    id: params.id,
    businessName: params.name,
    specialty: params.specialty,
    country: params.country,
    city: params.city,
    hasWebsite: params.hasWebsite,
    googleReviewCount: params.reviews,
    googleRating: params.rating,
    gbpStatus: params.gbp,
    ownerName: params.owner,
    ownerRole: params.ownerRole,
    source: params.source,
    sourcePartnerId: params.sourcePartnerId,
    stage: params.stage,
    lostReason: params.lostReason,
    notNowUntil: params.notNowUntil,
    score,
    channels,
    notes: params.notes || 'High potential private practice in prime commercial catchment.',
    assignedTo: params.assignedTo,
    createdAt: params.createdAt,
    lastActivityAt: '2026-09-28',
    ...params.milestones,
  };
}

